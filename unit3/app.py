"""Hugging Face Space entry point for the Financial Researcher crew.

The crewAI project in financial_researcher/ is used as-is: this file only imports ResearchCrew
from financial_researcher/src and wraps it in a Gradio UI with a live log of what the agents do.
"""
import os
import re
import sys
import threading
import time
from datetime import datetime
from pathlib import Path


def _hide_closed_loop_noise(unraisable) -> None:
    """On Spaces, importing crewAI leaves a few already-closed asyncio loops behind; when Python garbage-collects
    them it prints 'Exception ignored in BaseEventLoop.__del__ ... Invalid file descriptor: -1'. It's harmless
    (the app keeps working), so hide exactly that message and report everything else as usual."""
    if (getattr(unraisable.object, "__qualname__", "") == "BaseEventLoop.__del__"
            and isinstance(unraisable.exc_value, ValueError)
            and "Invalid file descriptor: -1" in str(unraisable.exc_value)):
        return
    sys.__unraisablehook__(unraisable)


sys.unraisablehook = _hide_closed_loop_noise

import gradio as gr  # noqa: E402
from dotenv import find_dotenv, load_dotenv  # noqa: E402

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "financial_researcher" / "src"))  # the crewAI project, unchanged
load_dotenv(find_dotenv(usecwd=True))  # local runs: OPENAI_API_KEY / SERPER_API_KEY from the nearest .env

from financial_researcher.crew import ResearchCrew  # noqa: E402

REQUIRED_KEYS = ["OPENAI_API_KEY", "SERPER_API_KEY"]
RUNS_DIR = ROOT / "output" / "runs"
DISCLAIMER = "⚠️ Generated by AI agents for research purposes only. Not financial advice; do not use for trading decisions."
EXAMPLES = ["Tesla", "NVIDIA", "Galp Energia", "ASML"]


def _short(text, n: int = 200) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= n else text[:n] + "…"


def describe_step(step) -> str | None:
    """Turn a crewAI step (tool call or final answer) into one log line."""
    tool = getattr(step, "tool", None)
    if tool:  # AgentAction: the agent used a tool
        return f"🔧 `{tool}`({_short(getattr(step, 'tool_input', ''), 120)}) → {_short(getattr(step, 'result', ''))}"
    if hasattr(step, "output"):  # AgentFinish: the agent produced its answer
        return "✅ agent finished its answer"
    return None


def strip_fences(markdown: str) -> str:
    """Models sometimes wrap the whole report in ```markdown fences; remove them so it renders."""
    return re.sub(r"^```(?:markdown|md)?\s*\n(.*)\n```\s*$", r"\1", markdown.strip(), flags=re.DOTALL)


def save_run(company: str, report: str, research: str) -> list[str]:
    slug = re.sub(r"[^a-z0-9]+", "-", company.lower()).strip("-") or "company"
    run_dir = RUNS_DIR / f"{datetime.now():%Y%m%d-%H%M%S}-{slug}"
    run_dir.mkdir(parents=True, exist_ok=True)
    (run_dir / "report.md").write_text(f"{report}\n\n---\n\n_{DISCLAIMER}_\n")
    (run_dir / "research.md").write_text(research)
    return [str(run_dir / "report.md"), str(run_dir / "research.md")]


def research(company: str):
    company = (company or "").strip()
    if not company:
        yield "Type a company name first.", "", "", "", None
        return
    missing = [k for k in REQUIRED_KEYS if not os.getenv(k)]
    if missing:
        yield f"⚠️ Missing {', '.join(missing)}: add them as Space secrets (Settings → Variables and secrets).", "", "", "", None
        return

    log: list[str] = [f"▶️ Researching **{company}**"]
    result: dict = {}
    crew = ResearchCrew().crew()
    crew.step_callback = lambda step: log.append(line) if (line := describe_step(step)) else None
    crew.task_callback = lambda out: log.append(f"📋 **{(out.agent or '').strip()}** finished: {out.name}")

    def kickoff():
        try:
            result["output"] = crew.kickoff(inputs={"company": company})
        except Exception as exc:  # noqa: BLE001 - shown in the UI
            result["error"] = f"{type(exc).__name__}: {exc}"

    worker = threading.Thread(target=kickoff, daemon=True)
    worker.start()
    start = time.time()
    while worker.is_alive():  # stream the log while the crew works
        yield f"⏳ Working… {time.time() - start:.0f}s", "", "", "  \n".join(log), None
        worker.join(timeout=1.5)

    if "error" in result:
        log.append(f"💥 {result['error']}")
        yield f"💥 The crew failed: {result['error']}", "", "", "  \n".join(log), None
        return
    report = strip_fences(result["output"].raw)
    research_notes = strip_fences(crew.tasks[0].output.raw if crew.tasks[0].output else "")
    files = save_run(company, report, research_notes)
    log.append(f"⏹️ Done in {time.time() - start:.0f}s")
    yield f"✅ Report on **{company}** ready in {time.time() - start:.0f}s", report, research_notes, "  \n".join(log), files


with gr.Blocks(title="Financial Researcher") as demo:
    gr.Markdown(
        "# 📈 Financial Researcher\n"
        "A [crewAI](https://crewai.com) crew researches a company on the web and writes a cited report: "
        "a **Senior Financial Researcher** (web search) followed by a **Market Analyst** (report writer).\n\n"
        f"_{DISCLAIMER}_"
    )
    company = gr.Textbox(label="Company", placeholder="e.g. Tesla")
    go = gr.Button("Research", variant="primary")
    gr.Examples(EXAMPLES, company, cache_examples=False)
    status = gr.Markdown()
    with gr.Tab("📄 Report"):
        report_md = gr.Markdown()
    with gr.Tab("🔎 Research notes & sources"):
        research_md = gr.Markdown()
    with gr.Tab("🪵 Live log"):
        log_md = gr.Markdown()
    with gr.Tab("⬇️ Files"):
        files = gr.File(file_count="multiple")
    outputs = [status, report_md, research_md, log_md, files]
    go.click(research, company, outputs, concurrency_limit=1)
    company.submit(research, company, outputs, concurrency_limit=1)

if __name__ == "__main__":
    demo.queue().launch(theme=gr.themes.Soft())
