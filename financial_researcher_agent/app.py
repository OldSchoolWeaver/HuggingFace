# ------------------------------------------------------------------ shared helpers
def _short(text, n: int = 200) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= n else text[:n] + "…"


def describe_step(step) -> str | None:
    """Turn a crewAI step (tool call or final answer) into one log line."""
    tool = getattr(step, "tool", None)
    if tool:  # AgentAction: the agent used a tool
        return f"🔧 `{tool}`({_short(getattr(step, 'tool_input', ''), 120)}) → {_short(getattr(step, 'result', ''))}"
    if hasattr(step, "output"):  # AgentFinish: the agent produced its answer
        return "✅ agent finished its answer"
    return None


def strip_fences(markdown: str) -> str:
    """Models sometimes wrap the whole report in ```markdown fences; remove them so it renders."""
    return re.sub(r"^```(?:markdown|md)?\s*\n(.*)\n```\s*$", r"\1", markdown.strip(), flags=re.DOTALL)


def save_run(kind: str, name: str, files: dict[str, str]) -> list[str]:
    """Save a run's markdown files under output/runs/<date>-<kind>-<name>/ and return their paths."""
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-") or kind
    run_dir = RUNS_DIR / f"{datetime.now():%Y%m%d-%H%M%S}-{kind}-{slug}"
    run_dir.mkdir(parents=True, exist_ok=True)
    for filename, text in files.items():
        (run_dir / filename).write_text(text)
    return [str(run_dir / f) for f in files]


def missing_keys() -> str | None:
    missing = [k for k in REQUIRED_KEYS if not os.getenv(k)]
    return f"⚠️ Missing {', '.join(missing)}: add them as Space secrets (Settings → Variables and secrets)." if missing else None


def run_with_live_log(crew, inputs: dict, log: list[str]):
    """Run crew.kickoff in a background thread. Yields ("running", seconds) every 1.5 s while it works,
    then ("done", CrewOutput) or ("error", message)."""
    crew.step_callback = lambda step: log.append(line) if (line := describe_step(step)) else None
    crew.task_callback = lambda out: log.append(f"📋 **{(out.agent or '').strip()}** finished: {out.name}")
    result: dict = {}

    def kickoff():
        try:
            result["output"] = crew.kickoff(inputs=inputs)
        except Exception as exc:  # noqa: BLE001 - shown in the UI
            result["error"] = f"{type(exc).__name__}: {exc}"

    worker = threading.Thread(target=kickoff, daemon=True)
    worker.start()
    start = time.time()
    while worker.is_alive():
        yield "running", time.time() - start
        worker.join(timeout=1.5)
    if "error" in result:
        log.append(f"💥 {result['error']}")
        yield "error", result["error"]
    else:
        log.append(f"⏹️ Done in {time.time() - start:.0f}s")
        yield "done", result["output"]


# ------------------------------------------------------------------ 📈 Financial Researcher
def research_company(company: str):
    company = (company or "").strip()
    if not company:
        yield "Type a company name first.", "", "", "", None
        return
    if problem := missing_keys():
        yield problem, "", "", "", None
        return

    log: list[str] = [f"▶️ Researching **{company}**"]
    crew = ResearchCrew().crew()
    start = time.time()
    for state, value in run_with_live_log(crew, {"company": company}, log):
        if state == "running":
            yield f"⏳ Working… {value:.0f}s", "", "", "  \n".join(log), None
        elif state == "error":
            yield f"💥 The crew failed: {value}", "", "", "  \n".join(log), None
        else:
            report = strip_fences(value.raw)
            notes = strip_fences(crew.tasks[0].output.raw if crew.tasks[0].output else "")
            files = save_run("research", company, {"report.md": f"{report}\n\n---\n\n_{DISCLAIMER}_\n", "research.md": notes})
            yield f"✅ Report on **{company}** ready in {time.time() - start:.0f}s", report, notes, "  \n".join(log), files


# ------------------------------------------------------------------ 🎯 Stock Picker
def _cell(value) -> str:
    return str(value).replace("|", "/").replace("\n", " ") if value not in (None, "") else "unknown"


def candidates_table(task_output) -> str:
    data = getattr(task_output, "pydantic", None)
    if not data:
        return strip_fences(getattr(task_output, "raw", "") or "")
    rows = "\n".join(f"| {_cell(c.name)} | `{_cell(c.ticker)}` | {_cell(c.reason)} |" for c in data.companies)
    return f"| Company | Ticker | Why it's trending |\n|---|---|---|\n{rows}\n"


def research_tables(task_output) -> str:
    data = getattr(task_output, "pydantic", None)
    if not data:
        return strip_fences(getattr(task_output, "raw", "") or "")
    rows = "\n".join(
        f"| {_cell(r.name)} | `{_cell(r.ticker)}` | {_cell(r.EPS)} | {_cell(r.Revenue_growth)} | {_cell(r.Gross_profit_margin)} "
        f"| {_cell(r.Return_on_equity)} | {_cell(r.Price_to_earnings)} | {_cell(r.Moving_average_convergence_divergence)} "
        f"| {_cell(r.Momentum)} | {_cell(r.Simple_moving_average_50)} | {_cell(r.Simple_moving_average_200)} | {_cell(r.metrics_as_of)} |"
        for r in data.research_list
    )
    table = ("| Company | Ticker | EPS | Revenue growth | Gross margin | ROE | P/E | MACD | Momentum | SMA 50 | SMA 200 | As of |\n"
             "|---|---|---|---|---|---|---|---|---|---|---|---|\n" + rows)
    details = "\n\n".join(
        f"### {r.name} (`{r.ticker}`)\n**Market position:** {r.market_position}\n\n**Outlook:** {r.future_outlook}\n\n"
        f"**Investment potential:** {r.investment_potential}"
        for r in data.research_list
    )
    return f"{table}\n\n_Metrics: Yahoo Finance via yfinance._\n\n{details}\n"


def pick_stocks(sector: str):
    sector = (sector or "").strip()
    if not sector:
        yield "Type a sector first.", "", "", "", "", None
        return
    if problem := missing_keys():
        yield problem, "", "", "", "", None
        return

    log: list[str] = [f"▶️ Picking stocks in **{sector}**"]
    crew = StockPicker().crew()
    inputs = {"sector": sector, "current_date": datetime.now().strftime("%Y-%m-%d")}
    start = time.time()
    for state, value in run_with_live_log(crew, inputs, log):
        if state == "running":
            yield f"⏳ Working… {value:.0f}s", "", "", "", "  \n".join(log), None
        elif state == "error":
            yield f"💥 The crew failed: {value}", "", "", "", "  \n".join(log), None
        else:
            decision = strip_fences(value.raw)
            candidates = candidates_table(crew.tasks[0].output)
            research = research_tables(crew.tasks[1].output)
            files = save_run("picks", sector, {
                "decision.md": f"{decision}\n\n---\n\n_{DISCLAIMER}_\n",
                "candidates.md": candidates,
                "research.md": research,
            })
            yield (f"✅ Picks for **{sector}** ready in {time.time() - start:.0f}s", decision, candidates, research,
                   "  \n".join(log), files)


